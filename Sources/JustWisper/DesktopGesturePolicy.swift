import Foundation

enum MouseRecordingBehavior: String, Codable, CaseIterable, Identifiable {
    case toggle, hold
    var id: String { rawValue }
    var title: String { self == .toggle ? "Toggle recording" : "Hold to record" }
}

enum RecordingOverlayStyle: String, Codable, CaseIterable, Identifiable {
    case classic, mini, none
    var id: String { rawValue }
    var title: String { rawValue.capitalized }
}

/// A rejected overlapping gesture never acquires release ownership.
struct HoldRecordingOwnership {
    enum Source { case keyboard, mouse }
    private(set) var owner: Source?
    mutating func begin(_ source: Source, available: Bool) -> Bool {
        guard available, owner == nil else { return false }
        owner = source
        return true
    }
    mutating func end(_ source: Source) -> Bool {
        guard owner == source else { return false }
        owner = nil
        return true
    }
    mutating func clear() { owner = nil }
}

/// Local/global mouse monitors cover disjoint apps. Paired-state checks also
/// suppress duplicate downs and orphan ups, without ever binding primary clicks.
struct MouseRecordingGesture {
    enum Action: Equatable { case toggle, beginHold, endHold }
    var button: Int?
    var behavior: MouseRecordingBehavior = .toggle
    private(set) var pressed = false

    static func isSupported(_ button: Int?) -> Bool { button == nil || [2, 3, 4].contains(button!) }
    mutating func receive(button eventButton: Int, down: Bool) -> Action? {
        guard let button, [2, 3, 4].contains(button), eventButton == button else { return nil }
        if down {
            guard !pressed else { return nil }
            pressed = true
            return behavior == .toggle ? .toggle : .beginHold
        }
        guard pressed else { return nil }
        pressed = false
        return behavior == .hold ? .endHold : nil
    }
}

/// Raw clipboard text is memory-only and expires three seconds after a newly
/// observed change. Enabling or restoring a clipboard does not make it recent.
struct RecentClipboardTracker {
    static let maximumAge: TimeInterval = 3
    private(set) var observedChangeCount: Int?
    private var capturedAt: Date?
    private var text: String?

    mutating func reset(changeCount: Int? = nil) {
        observedChangeCount = changeCount
        capturedAt = nil
        text = nil
    }
    static func allows(types: [String]) -> Bool {
        let lowered = types.map { $0.lowercased() }
        let rejected = ["concealed", "transient", "autogenerated", "auto-generated", "password", "onepassword", "1password", "agilebits", "lastpass", "bitwarden", "dashlane", "keepass", "keychain", "com.apple.security"]
        guard !lowered.contains(where: { type in rejected.contains(where: type.contains) }) else { return false }
        return lowered.contains { ["public.utf8-plain-text", "public.utf16-plain-text", "public.plain-text", "nsstringpboardtype"].contains($0) }
    }
    mutating func observe(changeCount: Int, types: [String], text: String?, at now: Date) {
        guard let previous = observedChangeCount else { reset(changeCount: changeCount); return }
        guard changeCount != previous else { expire(at: now); return }
        reset(changeCount: changeCount)
        guard Self.allows(types: types), let text = CapturedContext.sanitize(text, limit: 2000) else { return }
        self.text = text
        capturedAt = now
    }
    mutating func recent(at now: Date) -> String? {
        expire(at: now)
        return text
    }
    private mutating func expire(at now: Date) {
        guard let capturedAt else { return }
        let age = now.timeIntervalSince(capturedAt)
        if age < 0 || age > Self.maximumAge { text = nil; self.capturedAt = nil }
    }
}

struct ModeSwitcherSelection {
    private(set) var index: Int
    private let count: Int
    init(count: Int, selectedIndex: Int = 0) {
        self.count = max(0, count)
        index = count > 0 ? min(count - 1, max(0, selectedIndex)) : 0
    }
    mutating func move(_ delta: Int) {
        guard count > 0 else { return }
        index = (index + delta % count + count) % count
    }
    var selectedIndex: Int? { count > 0 ? index : nil }
}
